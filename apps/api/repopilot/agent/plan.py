"""Turning a task plus a measured repository into a validated implementation plan.

The contract with the model is deliberately narrow: it is shown real file paths and real file
contents, and it is asked for one JSON object. Everything that comes back is validated against
:mod:`repopilot.agent.schema`, and every path is checked against the files that actually exist
before the plan is accepted. A model that hallucinates ``src/app.py`` gets that entry dropped
with a recorded reason rather than silently steering Phase 2B into a file that is not there.
"""

from __future__ import annotations

import logging
from pathlib import Path

from pydantic import ValidationError

from repopilot.agent.llm import ChatClient, ChatMessage, LLMError, extract_json_object
from repopilot.agent.prompts import build_planner_prompt
from repopilot.agent.schema import FileSelection, ImplementationPlan, PlanStep
from repopilot.analysis.profile import RepositoryProfile
from repopilot.analysis.relevance import CandidateFile

logger = logging.getLogger("repopilot.agent.plan")

#: How many times to re-ask after the model replies with something that will not validate.
MAX_PLANNING_ATTEMPTS = 2


class PlanRejectedError(RuntimeError):
    """The model could not produce a usable plan."""


async def generate_plan(
    client: ChatClient,
    *,
    task: str,
    repository: str,
    profile: RepositoryProfile,
    candidates: list[CandidateFile],
    default_branch: str | None = None,
    root: Path | None = None,
    temperature: float = 0.0,
) -> tuple[ImplementationPlan, list[str]]:
    """Ask the model for a plan. Returns the plan and any notes about what was filtered out.

    ``root`` should be the run workspace so quoted contents come from the clone. When omitted,
    the plan is generated from the measured inventory alone.
    """
    if not candidates:
        raise PlanRejectedError(
            "no files in this repository look related to the task, so there is nothing to plan"
        )

    turns = build_planner_prompt(
        task=task,
        repository=repository,
        default_branch=default_branch,
        profile=profile,
        candidates=candidates,
        root=root,
    )
    messages = [ChatMessage(role=role, content=content) for role, content in turns]

    known_paths = {source.path for source in profile.files} | set(profile.manifests)
    known = known_paths | set(profile.test_configs) | set(profile.docs) | set(profile.top_level)

    last_error = ""
    for attempt in range(1, MAX_PLANNING_ATTEMPTS + 1):
        try:
            completion = await client.complete(messages, temperature=temperature, json_mode=True)
        except LLMError:
            raise  # transport/auth problems are not fixed by asking again

        try:
            raw = extract_json_object(completion.text)
        except LLMError as exc:
            last_error = str(exc)
            logger.warning("planning attempt %d returned unusable JSON: %s", attempt, exc)
            messages = [
                *messages,
                ChatMessage(role="assistant", content=completion.text[:2_000]),
                ChatMessage(
                    role="user",
                    content=(
                        f"That was not valid JSON ({exc}). Reply with only the JSON object, "
                        "no prose and no code fences."
                    ),
                ),
            ]
            continue

        try:
            plan = ImplementationPlan.model_validate(raw)
        except ValidationError as exc:
            last_error = _summarise_validation_error(exc)
            logger.warning("planning attempt %d failed validation: %s", attempt, last_error)
            messages = [
                *messages,
                ChatMessage(role="assistant", content=completion.text[:2_000]),
                ChatMessage(
                    role="user",
                    content=(
                        f"That JSON did not match the required shape ({last_error}). "
                        "Reply with only a corrected JSON object."
                    ),
                ),
            ]
            continue

        plan.model = completion.model or client.model
        plan.prompt_tokens = completion.prompt_tokens
        plan.completion_tokens = completion.completion_tokens

        plan, dropped = _drop_hallucinated_paths(plan, known)
        logger.info(
            "plan generated by %s: %d steps, %d files, %d hallucinated paths dropped",
            plan.model,
            len(plan.steps),
            len(plan.relevant_files),
            len(dropped),
        )
        return plan, dropped

    raise PlanRejectedError(
        f"the model did not return a valid implementation plan after {MAX_PLANNING_ATTEMPTS} "
        f"attempts ({last_error})"
    )


def _drop_hallucinated_paths(
    plan: ImplementationPlan, known: set[str]
) -> tuple[ImplementationPlan, list[str]]:
    """Remove any referenced path that is neither a real file nor a file the plan will create.

    The model is told to only use real paths, but instructions are not enforcement. This is.

    Only ``modify`` and ``read`` selections must already exist. A selection with role ``add`` is
    the plan proposing a new file, so dropping those for being absent would delete the most
    useful part of many plans and leave Phase 2B with nothing to create.
    """
    kept: list[FileSelection] = []
    dropped: list[str] = []
    will_create: set[str] = set()

    for selection in plan.relevant_files:
        if selection.role == "add":
            will_create.add(selection.path)
            kept.append(selection)
        elif selection.path in known:
            kept.append(selection)
        else:
            dropped.append(selection.path)

    if not dropped:
        return plan, []

    allowed = {s.path for s in kept} | will_create
    steps: list[PlanStep] = []
    for step in plan.steps:
        real_files = [f for f in step.files if f in allowed]
        dropped.extend(f for f in step.files if f not in allowed)
        steps.append(step.model_copy(update={"files": real_files}))

    note = (
        f"Discarded {len(set(dropped))} path(s) the plan referenced that do not exist in the "
        "repository: " + ", ".join(sorted(set(dropped)))
    )
    logger.warning(note)

    return (
        plan.model_copy(
            update={
                "relevant_files": kept,
                "steps": steps,
                "risks": [*plan.risks, note],
            }
        ),
        sorted(set(dropped)),
    )


def _summarise_validation_error(exc: ValidationError) -> str:
    """Turn a pydantic error into one line an operator can act on."""
    parts = []
    for error in exc.errors()[:4]:
        location = ".".join(str(item) for item in error.get("loc", ())) or "(root)"
        parts.append(f"{location}: {error.get('msg', 'invalid')}")
    return "; ".join(parts)
